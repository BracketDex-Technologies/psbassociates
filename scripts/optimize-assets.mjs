import fs from 'node:fs/promises';
import { createHash } from 'node:crypto';
import sharp from 'sharp';
import { transform } from 'esbuild';

// Preserve editable CSS sources. Ship a single minified, content-addressed bundle
// per layout so changes cannot be hidden by a stale browser/CDN cache.
export async function buildOptimizedAssets() {
  const shared = ['fonts', 'style', 'modern', 'home', 'integrations', 'motion', 'specialist'];
  const styles = {};
  for (const layout of ['site', 'forms']) {
    const names = [...shared, ...(layout === 'forms' ? ['contact'] : []), 'refinements'];
    const source = (await Promise.all(names.map(name => fs.readFile(`dist/assets/${name}.css`, 'utf8')))).join('\n');
    const { code } = await transform(source, { loader: 'css', minify: true, target: 'es2020' });
    const digest = createHash('sha256').update(code).digest('hex').slice(0, 12);
    styles[layout] = `/assets/${layout}-${digest}.css`;
    await fs.writeFile(`dist${styles[layout]}`, code);
  }
  const portraits = {};
  // Only obsolete bundles generated by this module are removed, never source CSS.
  for (const file of await fs.readdir('dist/assets')) {
    if (/^(site|forms)-[a-f0-9]{12}\.css$/.test(file) && !Object.values(styles).includes(`/assets/${file}`)) {
      await fs.unlink(`dist/assets/${file}`);
    }
  }
  for (const name of ['pavan', 'sagar', 'bharadwaj']) {
    const source = `dist/assets/${name}.webp`;
    portraits[name] = await sharp(source).metadata();
    for (const width of [128, 256, 480]) {
      await sharp(source).resize({ width, withoutEnlargement: true }).webp({ quality: 82 }).toFile(`dist/assets/${name}-${width}.webp`);
    }
  }
  return { styles, portraits };
}

export function optimizePageHtml(html, current, { styles, portraits }) {
  const stylesheet = styles[['contact', 'careers'].includes(current) ? 'forms' : 'site'];
  html = html.replace(/<link rel="preconnect"[^>]*>/g, '')
    .replace(/<link[^>]*rel="stylesheet"[^>]*>/g, '')
    .replace('</head>', `<link rel="preload" href="/assets/fonts/dm-sans-latin.woff2" as="font" type="font/woff2" crossorigin><link rel="preload" href="/assets/fonts/manrope-latin.woff2" as="font" type="font/woff2" crossorigin><link rel="stylesheet" href="${stylesheet}"></head>`)
    .replaceAll('aria-label="Toggle navigation"', 'aria-label="Menu"')
    .replaceAll('Menu <span>☰</span>', 'Menu <span aria-hidden="true">☰</span>')
    .replace('<main id="main">', '<main id="main" tabindex="-1">');
  html = html.replace(/<img src="\/assets\/(pavan|sagar|bharadwaj)\.webp"([^>]*)>/g, (_, name, attributes) => {
    const { width, height } = portraits[name];
    const avatar = attributes.includes('width="52"');
    const sizes = avatar ? '52px' : html.includes('class="partner-profile"')
      ? '(max-width: 650px) calc(100vw - 40px), (max-width: 900px) 45vw, 440px'
      : '(max-width: 650px) 94px, (max-width: 1100px) 30vw, 400px';
    const dimensions = /\bwidth=/.test(attributes) ? '' : ` width="${width}" height="${height}"`;
    return `<img src="/assets/${name}-${avatar ? 128 : 480}.webp" srcset="${[128, 256, 480].map(w => `/assets/${name}-${w}.webp ${w}w`).join(', ')}, /assets/${name}.webp ${width}w" sizes="${sizes}"${attributes}${dimensions} decoding="async">`;
  });
  return html;
}
